def structural_kind(rel_path: str) -> str | None:
    """The Writer kind of a structural Change artifact, or None for prose and code.

    Roadmap item 1: these files are structure the Worker never writes by hand;
    `deltafuse artifact write` writes them and the Core rewrites their status.
    """
    parts = posix_relpath(rel_path).split("/")
    if len(parts) == 3 and parts[:2] == ["docs", "decisions"] and parts[2].startswith("DEC-") and parts[2].endswith(".md"):
        return "decision"
    if len(parts) < 4 or parts[0] != "docs" or parts[1] != "changes":
        return None
    tail = parts[3:]
    if tail == ["routing.yaml"]:
        return "routing"
    if tail == ["spec-delta.md"]:
        return "spec-delta"
    if len(tail) == 2 and tail[1].endswith(".md"):
        return {"slices": "slice", "tasks": "task"}.get(tail[0])
    return None


def _git(root: Path, *args: str, text: bool = True) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(["git", *args], cwd=root, capture_output=True, text=text, check=False)
    except OSError as ex:  # no git at all: answer as git would for a missing revision
        empty = "" if text else b""
        return subprocess.CompletedProcess(["git", *args], 127, empty, str(ex) if text else str(ex).encode())


def _git_bytes(product_root: Path, ref: str, rel_path: str) -> bytes | None:
    """File bytes at a revision (or the index, INDEX); None when the file (or the revision) is absent."""
    spec = f":{rel_path}" if ref == INDEX else f"{ref}:{rel_path}"
    # `cat-file`, not `show`: `git show <rev>:<path>` first tries the argument as a file name, and
    # on Windows without core.longpaths a long one dies with "Filename too long" - the file then
    # read as absent, and an archived Change's record as a deletion (re-probe 2026-11-17).
    proc = _git(product_root, "cat-file", "blob", spec, text=False)
    return proc.stdout if proc.returncode == 0 else None


def _git_show(product_root: Path, ref: str, rel_path: str) -> str | None:
    """File content at a revision, undecodable bytes replaced; None when absent."""
    data = _git_bytes(product_root, ref, rel_path)
    return None if data is None else data.decode("utf-8", errors="replace")


def _bytes_at(product_root: Path, rel_path: str, *, head: str | None) -> bytes | None:
    if head:
        return _git_bytes(product_root, head, rel_path)
    path = product_root / rel_path
    return path.read_bytes() if path.is_file() else None


def _content_at(product_root: Path, rel_path: str, *, head: str | None) -> str | None:
    """Text at ``head`` (lenient decode), else in the working tree (strict UTF-8)."""
    if head:
        return _git_show(product_root, head, rel_path)
    path = product_root / rel_path
    return path.read_text(encoding="utf-8") if path.is_file() else None


