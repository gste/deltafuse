def archive_move_judge(product_root: Path, *, base: str | None, head: str | None) -> Callable[[str], bool]:
    """Whether a missing file of a Change was moved by `deltafuse archive`, not deleted.

    True for `docs/changes/<dir>/<file>` absent from the judged tree when the Change that held it
    at the base is archived there (same id, status `archived`) and the archive holds `<file>`."""
    root = Path(product_root)
    archives: dict[str, str] | None = None

    def archive_homes() -> dict[str, str]:
        nonlocal archives
        if archives is None:
            archives = {}
            if head is None:
                names = [p.relative_to(root).as_posix() for p in (root / ARCHIVE_HOME).glob("*/change.yaml")]
            else:
                listing = ("ls-files", "--", ARCHIVE_HOME) if head == INDEX else (
                    "ls-tree", "-r", "--name-only", head, "--", ARCHIVE_HOME)
                try:
                    names = _git_names(root, *listing, what="list archived Changes")
                except LeashError:
                    names = []
            for name in names:
                parts = name.split("/")
                if len(parts) != 5 or parts[4] != "change.yaml":
                    continue
                try:
                    data = yaml.safe_load((_bytes_at(root, name, head=head) or b"").decode("utf-8"))
                except (UnicodeDecodeError, yaml.YAMLError):
                    continue
                if isinstance(data, dict) and data.get("status") == "archived" and isinstance(data.get("id"), str):
                    archives.setdefault(data["id"], "/".join(parts[:4]))
        return archives

    def judge(raw: str) -> bool:
        parts = posix_relpath(raw).split("/")
        if len(parts) < 4 or parts[:2] != ["docs", "changes"]:
            return False
        if _bytes_at(root, "/".join(parts), head=head) is not None:
            return False  # still there: not a move
        before = _bytes_at(root, "/".join(parts[:3]) + "/change.yaml", head=base or "HEAD")
        try:
            data = yaml.safe_load((before or b"").decode("utf-8"))
        except (UnicodeDecodeError, yaml.YAMLError):
            return False
        change_id = data.get("id") if isinstance(data, dict) else None
        home = archive_homes().get(change_id) if isinstance(change_id, str) else None
        return home is not None and _bytes_at(root, home + "/" + "/".join(parts[3:]), head=head) is not None

    return judge


def core_journal_errors(
    product_root: Path,
    name: str,
    *,
    base: str | None = None,
    head: str | None = None,
) -> list[str]:
    """DF3-007: why a Core journal diff is not a Core-shaped append (empty = valid).

    The Worker runs `deltafuse advance` and the human runs `deltafuse decide`
    inside the same working tree, so the journals legitimately change between
    commits. A diff is accepted only when it appends entries the Core would have
    written: existing lines untouched, every transition receipt digest intact
    and the chain replayable, the gate journal chain and head verified.
    """
    from deltafuse.core import gate_receipts
    from deltafuse.core.transitions import _receipt, receipt_chain_errors

    root = Path(product_root)
    if name == "journal-head":
        # The head digest moves with every gate receipt; it is valid exactly
        # when it matches the verified gate journal.
        return gate_receipts.journal_errors(root)
    rel = f".deltafuse/{name}"
    old, new = _journal_lines(root, rel, base=base, head=head)
    if new[: len(old)] != old:
        return ["existing entries were edited, removed or reordered; Core journals are append-only"]
    appended = new[len(old):]
    errors: list[str] = []
    if name == "transitions.jsonl":
        touched: set[str] = set()
        for number, raw in enumerate(appended, start=len(old) + 1):
            try:
                entry = json.loads(raw)
            except json.JSONDecodeError:
                errors.append(f"line {number} is not JSON")
                continue
            if not isinstance(entry, dict) or entry.get("kind") not in CORE_RECEIPT_KINDS:
                errors.append(f"line {number} is not a Core transition receipt")
                continue
            body = {key: value for key, value in entry.items() if key != "receipt"}
            if entry.get("receipt") != _receipt(body):
                errors.append(f"line {number}: receipt digest does not match the entry")
                continue
            if isinstance(entry.get("change"), str):
                touched.add(entry["change"])
        if errors:
            return errors
        dirs = _change_dirs(root)
        for change_id in sorted(touched):
            change_dir = dirs.get(change_id)
            if change_dir is not None:
                errors.extend(
                    f"{change_id}: {err}" for err in receipt_chain_errors(root, change_dir)
                )
        return errors
    if name == "gate-journal.jsonl":
        for number, raw in enumerate(appended, start=len(old) + 1):
            try:
                entry = json.loads(raw)
            except json.JSONDecodeError:
                errors.append(f"line {number} is not JSON")
                continue
            # journal_errors skips legacy lines, but has_click still reads
            # them: an appended line without the current receipt format
            # would count as a click without any integrity claim.
            if not isinstance(entry, dict) or entry.get("receipt_version") != gate_receipts.RECEIPT_VERSION:
                errors.append(f"line {number} is not a current-format gate receipt")
        if errors:
            return errors
        return gate_receipts.journal_errors(root)
    return [f"unknown Core journal '{name}'"]


def core_status_writes(
    product_root: Path,
    *,
    base: str | None = None,
    head: str | None = None,
) -> dict[str, list[str]]:
    """Task and slice files the Core rewrote through `deltafuse state` since ``base``.

    `deltafuse state` is how a Worker asks the Core to move a slice or task
    status; the Core rewrites the frontmatter and appends an artifact-status
    receipt. Those files lie outside the step envelope on purpose - a Worker
    must not hand-edit them - so the guard recognises the Core's rewrite by its
    receipt and by its content: only `status` changed, from the first receipt's
    `from` to the last receipt's `to`, the rest of the frontmatter and the body
    as before. Maps each path to the reasons it fails (empty = a pure Core
    status write).
    """
    root = Path(product_root)
    old, new = _journal_lines(root, ".deltafuse/transitions.jsonl", base=base, head=head)
    if new[: len(old)] != old:
        return {}  # core_journal_errors reports the rewrite; nothing is vouched for
    dirs = _change_dirs(root)
    moves: dict[str, list[dict[str, Any]]] = {}
    rewound: set[str] = set()  # Changes a rewind took back since the base, as the rows go by
    reset: set[str] = set()  # files whose first status write since the base follows such a rewind
    for entry in _json_rows(new[len(old):]):
        if entry.get("kind") == "gap-reopen":
            rewound.add(str(entry.get("change")))
        if entry.get("kind") != "artifact-status":
            continue
        folder = {"task": "tasks", "slice": "slices"}.get(str(entry.get("artifact")))
        change_dir = dirs.get(str(entry.get("change")))
        if folder is None or change_dir is None or not isinstance(entry.get("artifact_id"), str):
            continue
        home = (change_dir / folder).relative_to(root).as_posix()
        rel = (change_dir / folder / f"{entry['artifact_id']}.md").relative_to(root).as_posix()
        recorded = entry.get("path")
        if isinstance(recorded, str):
            # A task file may be TASK-NNN-<slug>.md; the Core records which one
            # it rewrote. Only a file of this Change's folder is ever accepted.
            recorded = posix_relpath(recorded)
            if recorded.startswith(home + "/") and "/" not in recorded[len(home) + 1:]:
                rel = recorded
        if rel not in moves and str(entry.get("change")) in rewound:
            reset.add(rel)
        moves.setdefault(rel, []).append(entry)

    out: dict[str, list[str]] = {}
    for rel, entries in moves.items():
        reasons: list[str] = []
        try:
            before_meta, before_body = parse_frontmatter(_git_show(root, base or "HEAD", rel) or "")
            after_meta, after_body = parse_frontmatter(_content_at(root, rel, head=head) or "")
        except Exception as ex:
            out[rel] = [f"cannot compare with the base: {ex}"]
            continue
        # A rewind (`decide --gap`, a rejected accepted specification) puts slices back to `draft`
        # and implemented tasks back to `declared` under its own receipt, not an `artifact-status` one; with
        # the step's base before the rewind, the status there is the one the rewind took away.
        if rel not in reset and before_meta.get("status") != entries[0].get("from"):
            reasons.append(f"status at the base is not the receipt's '{entries[0].get('from')}'")
        if after_meta.get("status") != entries[-1].get("to"):
            reasons.append(f"status is not the receipt's '{entries[-1].get('to')}'")
        rest_before = {k: v for k, v in before_meta.items() if k != "status"}
        rest_after = {k: v for k, v in after_meta.items() if k != "status"}
        if rest_before != rest_after:
            reasons.append("frontmatter changed beyond status")
        # Line endings are not content: the base is read as bytes of the blob, the working file
        # as text, so a task committed with CRLF read as "body changed" after `deltafuse state`.
        if _eol_text(before_body).strip() != _eol_text(after_body).strip():
            reasons.append("body changed")
        out[rel] = reasons
    return out


def _eol_text(text: str) -> str:
    return text.replace("\r\n", "\n")


def _core_evidence(
    product_root: Path, rel: str, *, change: str, task: str, phase: str, head: str | None
) -> bool:
    """The record at ``rel`` is one `deltafuse evidence` stamped, for this Change, task and phase."""
    from deltafuse.core.evidence import evidence_stamp_error

    data = _bytes_at(Path(product_root), rel, head=head)
    if data is None:
        return False
    try:
        record = yaml.safe_load(data.decode("utf-8"))
    except (UnicodeDecodeError, yaml.YAMLError):
        return False
    if not isinstance(record, dict) or evidence_stamp_error(record, Path(product_root)) is not None:
        return False
    return record.get("change") == change and record.get("task") == task and record.get("phase") == phase


def collect_chain_envelopes(
    product_root: Path,
    *,
    base: str | None = None,
    dirty: list[str] | None = None,
    head: str | None = None,
) -> list[dict[str, Any]]:
    """Envelopes of the lifecycle steps each Change worked through since ``base``.

    The ready queue names only the next step, so it alone judges a finished
    step's writes against the step that follows it: request.md written by
    intake reads as outside the analyze envelope, and a commit right after
    `deltafuse advance` is refused. The steps are taken from the transition
    receipts, which core_journal_errors verifies: from the step after the last
    gate at ``base`` up to the step after the last gate now.

    Declare and implement are per task, and task progress is not in the
    transition chain. Their envelopes come from the tasks whose file changed
    since ``base`` - `deltafuse state` rewrites the task file on every task
    transition - so a task the Worker never touched adds no paths.
    """
    root = Path(product_root)
    last_gates, step_after = _last_gates, _step_after

    rel = ".deltafuse/transitions.jsonl"
    at_base, now = _journal_lines(root, rel, base=base, head=head)
    base_last, now_last = last_gates(at_base), last_gates(now)
    changed = {posix_relpath(path) for path in (dirty or [])}

    def rewinds(lines: list[str]) -> dict[str, list[str]]:
        out: dict[str, list[str]] = {}
        for entry in _json_rows(lines):
            gate = rewind_gate(entry)
            if gate is not None and isinstance(entry.get("change"), str):
                out.setdefault(entry["change"], []).append(gate)
        return out

    # Change -> the gates its rewinds since the base went back to (the journal is append-only).
    seen = rewinds(at_base)
    rewound_since_base = {
        change_id: gates[len(seen.get(change_id, [])):] for change_id, gates in rewinds(now).items()
    }

    final_gate = STEP_CONTRACTS[STEP_ORDER[-1]]["gate"]
    envelopes: list[dict[str, Any]] = []
    # R6: a Change archived in this diff counts like a live one (a live one of that id wins).
    judged = {**_archived_in_diff(root, changed), **_change_dirs(root)}
    for change_id, change_dir in judged.items():
        low, high = step_after(base_last.get(change_id)), step_after(now_last.get(change_id))
        if rewound_since_base.get(change_id):
            # The chain since base went back (to Analyze, to Specify, to Implement) and on from there.
            low = min([low] + [step_after(gate) for gate in rewound_since_base[change_id]])
        elif base_last.get(change_id) == final_gate:
            # FW-11: converged at the base and not reopened since - no step is left to write for.
            # (`step_after` of the last gate is the last step, so its envelope stayed open for good.)
            continue
        if high < low:
            continue  # a rewound chain is receipt_chain_errors' business, not a wider fence
        rel_dir = change_dir.relative_to(root).as_posix()
        for step in STEP_ORDER[low : high + 1]:
            items: list[WorkItem] = []
            if step in {"declare", "implement"}:
                # gemma-31b M01 (2026-09-26): evidence written, the gate advanced and the
                # step closed in one go, `state` called later - the task file was not
                # dirty yet, so its own evidence was judged against the step after it.
                # A task whose evidence for this step is dirty is the step's task too.
                phases = {"declare": ("red",), "implement": ("green", "regression")}[step]
                for task_id, _, task_file, _ in _load_tasks(change_dir):
                    task_rel = task_file.relative_to(root).as_posix()
                    # df-leash #7: only a record `deltafuse evidence` wrote for this task and
                    # phase - any file at that path opened the task's envelope, a never-declared
                    # task's product paths included, also while the human was deciding.
                    wrote_evidence = any(
                        f"{rel_dir}/evidence/{phase}/{task_id}.yaml" in changed
                        and _core_evidence(
                            root, f"{rel_dir}/evidence/{phase}/{task_id}.yaml",
                            change=change_id, task=task_id, phase=phase, head=head,
                        )
                        for phase in phases
                    )
                    if (task_rel in changed or wrote_evidence) and task_declared_in_time(
                        root, change_id, task_rel, head=head
                    ):
                        items.append(
                            _item_for_step(
                                step, change_id=change_id, path=rel_dir, task=task_id,
                                task_path=task_rel, reason="receipt chain since base",
                            )
                        )
            else:
                items.append(
                    _item_for_step(step, change_id=change_id, path=rel_dir, reason="receipt chain since base")
                )
            for item in items:
                env = build_envelope(item, root)
                if env:
                    envelopes.append(env)
    return envelopes


def check_paths(
    rel_paths: list[str],
    envelopes: list[dict[str, Any]] | None = None,
    *,
    envelope: dict[str, Any] | None = None,  # one envelope, the bench's form of the call
    baseline: str = "draft",
    product_root: Path | None = None,
    base: str | None = None,
    head: str | None = None,
) -> list[str]:
    """Return violation messages for dirty paths.

    A path is allowed when a ready envelope covers it. Code/ops/deploy
    paths with no covering Change are orphans. `docs/spec/**` is an
    orphan only after `project.baseline: accepted` (Bootstrap may write
    spec while the baseline is draft). Ready step + uncovered Change
    artifact is still an LS-002 miss.

    Core journals (DF3-007): with ``product_root`` they are verified against
    ``base`` instead of refused outright, because every `deltafuse advance`
    and `decide` appends to them; without it any change is refused.
    """
    if envelopes is None:
        env_list = [envelope] if envelope is not None else []
    else:
        env_list = list(envelopes)
    errors: list[str] = []
    steps = [str(env.get("step") or "?") for env in env_list]
    step_label = ", ".join(dict.fromkeys(steps)) if steps else ""
    # Say what the phase is for: a refusal alone sent a Worker into repeating it.
    phase_hint = (
        " (declare writes tests only; product code is written in implement)"
        if step_label == "declare"
        else ""
    )
    status_writes = (
        core_status_writes(product_root, base=base, head=head) if product_root is not None else {}
    )
    vouched = vouched_digests(product_root, head=head) if product_root is not None else {}
    human = human_decision_judge(product_root, base=base, head=head) if product_root is not None else None
    archived = archive_move_judge(product_root, base=base, head=head) if product_root is not None else None
    for raw in _unique(rel_paths):
        # DF3-007 runs before the exemptions: `.deltafuse/**` is exempt as a
        # whole, so checking it second would make the Core-owned guard dead code.
        top, _, tail = posix_relpath(raw).partition("/")
        if (
            top == ".deltafuse" and tail == "lock.yaml" and product_root is not None
            and _bytes_at(Path(product_root), LOCK_REL, head=head) is None
        ):
            # df-leash #6: the pin is what tells the hook a branch has DeltaFuse at all. Dropped
            # from the index (`git rm --cached`) it read as an exempt `.deltafuse/**` change, and
            # from the next commit on the hook skipped as on a branch without DeltaFuse.
            errors.append(
                f"leash: '{raw}' is removed; it pins DeltaFuse on this branch and only the human "
                "removes DeltaFuse (in a commit of their own, `git commit --no-verify`)"
            )
            continue
        if top == ".deltafuse" and tail in CORE_OWNED:
            if product_root is not None and tail in CORE_JOURNALS:
                reasons = core_journal_errors(product_root, tail, base=base, head=head)
                if not reasons:
                    continue
                errors.extend(
                    f"leash: '{raw}' changed outside the deltafuse CLI: {reason} (DF3-007)"
                    for reason in reasons
                )
                continue
            errors.append(
                f"leash: '{raw}' is Core-owned; mutate it only through "
                f"{CORE_OWNED_WRITER.get(tail, 'the deltafuse CLI')} (DF3-007)"
            )
            continue
        if raw.startswith(".git/") or is_exempt_path(raw):
            continue
        if human is not None and human(raw):
            continue  # written by the human's `deltafuse decide`, as its receipt or archive shows
        if archived is not None and archived(raw):
            continue  # moved by `deltafuse archive`: the file is in the Change's archive
        if _covered_by(raw, env_list) is not None:
            if product_root is not None:
                errors.extend(hand_written_errors(product_root, raw, head=head, vouched=vouched))
            continue
        if posix_relpath(raw) == CATALOG_REL and product_root is not None:
            # The catalog belongs to the human, and no step envelope holds it.
            # `deltafuse capability propose` adds a draft in Analyze and leaves
            # the digest of what it wrote; bytes no receipt vouches for are a
            # hand edit (q8 decision).
            if _bytes_digest(product_root, raw, head=head) in vouched.get(CATALOG_REL, set()):
                continue
            # Not vouched: fall through to the ordinary checks. The catalog is
            # the human's file and a human edit is not a Worker violation.
        status_reasons = status_writes.get(posix_relpath(raw))
        if status_reasons is not None:
            if not status_reasons:
                continue  # a `deltafuse state` rewrite, vouched for by its receipt
            errors.extend(
                f"leash: '{raw}' is outside the {step_label} write envelope and not a pure "
                f"Core status write: {reason}"
                for reason in status_reasons
            )
            continue
        if is_product_path(raw, baseline=baseline, product_root=product_root):
            if not env_list:
                errors.append(f"leash: '{raw}' is not covered by any Change")
            else:
                errors.append(
                    f"leash: '{raw}' is outside the {step_label} write envelope{phase_hint}"
                )
            continue
        if product_root is not None and reopen_archive_path(product_root, raw):
            continue  # written by the human's `deltafuse decide --status reopened`
        if product_root is not None and reopened_red_path(product_root, raw):
            # a reopened task is declared again past Declare; its Red is still the Core's
            errors.extend(hand_written_errors(product_root, raw, head=head, vouched=vouched))
            continue
        if is_change_artifact(raw):
            # FW-11: whether or not a step is ready - a file of a Change no envelope covers was
            # judged only while some envelope was open, so a converged Change's files were free.
            # gemma-334c/glm47flash: a Worker put the Writer's input JSON in a
            # `.deltafuse/tmp/` inside the Change directory (224 refusals in two
            # runs); the exemption is for the one at the product root.
            scratch = (
                " (the Writer's input file belongs in `.deltafuse/tmp/` at the product root, "
                "not inside the Change directory)"
                if "/.deltafuse/tmp/" in posix_relpath(raw)
                else ""
            )
            errors.append(
                f"leash: '{raw}' is outside the {step_label} write envelope{scratch}"
                if env_list else
                f"leash: '{raw}' is a Change file no open step may write{scratch}"
            )
            continue
        if matches_contract_globs(raw, SPEC_WRITE_GLOBS):
            continue  # `project.baseline: draft` - Bootstrap writes the specification freely
        if product_root is not None and structural_kind(raw) == "decision" and (
            _bytes_at(Path(product_root), posix_relpath(raw), head=head) is not None
        ):
            # FW-20: a Decision lies in no step's envelope and is not product code, so the
            # hand-written check - made only for a covered path - never ran for it.
            errors.extend(hand_written_errors(product_root, raw, head=head, vouched=vouched))
            continue
        # R5 (FW-7): judged like product code - it was not judged at all.
        errors.append(
            (f"leash: '{raw}' is outside the {step_label} write envelope" if env_list
             else f"leash: '{raw}' is not covered by any Change")
            + OUTSIDE_CODE_ROOTS
        )
    return errors



def ignored_product_files(product_root: Path) -> list[str]:
    """Untracked files git ignores that lie in the product's code roots (FW-18).

    The leash listed untracked files with `--exclude-standard`, so `src/hidden.py` named by a
    `.gitignore` line was invisible to the leash, to `advance` and to CI. A directory git ignores
    as a whole (`target/`, `node_modules/`, an ignored `__pycache__/`) is build output and is not
    listed: that is thousands of files the human told git to leave alone, and `.gitignore` itself
    is judged.
    """
    root = Path(product_root)
    layout = product_layout(root)
    listing = ["ls-files", "--others", "--ignored", "--exclude-standard"]
    out: list[str] = []
    for name in _git_names(root, *listing, "--directory", what="list ignored files"):
        if not name.endswith("/"):
            out.append(name)
            continue
        folder = name.rstrip("/")
        if _git(root, "check-ignore", "-q", "--", folder).returncode == 0:
            continue  # the directory itself is ignored
        # Named as one entry only because every file in it is ignored, each by its own rule.
        out += _git_names(root, *listing, "--", folder, what="list ignored files")
    return [name for name in _unique(out) if layout.is_guarded(name)]


def git_dirty_paths(
    product_root: Path,
    *,
    base: str | None = None,
    head: str | None = None,
    since: str | None = None,
    ignored: bool = False,
) -> list[str]:
    """Changed paths as repo-relative posix names.

    ``since`` (`advance`, df-leash #2): the working tree against HEAD plus what every commit
    after ``since`` on this line changed - merge commits excepted, whose changes come from
    another line that CI judges - so a `git commit --no-verify` inside a step is still judged.

    DF3-003 / SEC-01: pass ``base`` (and optionally ``head``) with exact SHAs to
    diff a commit range — a clean PR/push checkout has no local diff, so CI must
    judge the committed range. Untracked files remain a separate always-on check.
    ``head=INDEX`` (the pre-commit hook): the staged changes against HEAD, which is
    what the commit records; untracked and unstaged files are not in it.
    ``ignored`` (the leash; not the evidence record of what a step changed): also the untracked
    files git ignores inside the code roots - see ignored_product_files.
    """
    root = product_root.resolve()
    probe = _git(root, "rev-parse", "--show-toplevel")
    if probe.returncode != 0:
        err = (probe.stderr or probe.stdout or "git rev-parse failed").strip()
        raise LeashError(f"leash needs a git repository: {err}")
    # --no-renames (df-leash #5): with rename detection a `git mv src/app.py docs/intake/app.py`
    # lists only the new path, and the product file's removal is never judged.
    diff_args = ["diff", "--name-only", "--no-renames"]
    if head == INDEX:
        diff_args.append("--cached")
    if base:
        # Three dots (df-leash #15): what `head` changed since it left `base`'s line. Two dots
        # compared the trees, so commits the base branch got after the PR branched (a hotfix
        # merged by someone else) read as the PR's writes.
        diff_args.append(f"{base}...{head or 'HEAD'}")
    else:
        # A repository with no commits has no HEAD to diff against, and git says
        # so in its own words ("fatal: ambiguous argument 'HEAD'"). That is the
        # state of every freshly inited product at the moment run/SKILL.md tells
        # the Worker to run leash. Diffing the empty tree instead would list the
        # whole scaffold as the Worker's writes and bury the real answer under it.
        if _git(root, "rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
            raise LeashError(
                "leash needs one commit to diff against and this repository has no commit yet, "
                "so there is no baseline a write envelope can be judged against. Make an initial "
                "commit of the installed scaffold (`git add -A` then `git commit`), then run "
                "`deltafuse leash` again"
            )
        diff_args.append("HEAD")
    tracked = _git_names(root, *diff_args, what="read git diff")
    if head == INDEX:
        return _unique(tracked)
    committed: list[str] = []
    if since:
        listing = _git(root, "rev-list", "--no-merges", "--first-parent", f"{since}..HEAD")
        if listing.returncode != 0:
            err = (listing.stderr or listing.stdout or "git rev-list failed").strip()
            raise LeashError(f"leash could not list the step's commits: {err}")
        for commit in (line.strip() for line in listing.stdout.splitlines() if line.strip()):
            committed += _git_names(
                root, "diff-tree", "--no-commit-id", "--name-only", "-r", "--no-renames", "--root", commit,
                what="read a commit of the step",
            )
    untracked = _git_names(root, "ls-files", "--others", "--exclude-standard", what="list untracked files")
    hidden = ignored_product_files(root) if ignored else []
    # _unique normalizes slashes and drops blank lines.
    return _unique(tracked + committed + untracked + hidden)


def step_base(product_root: Path, change_dir: Path) -> str | None:
    """The commit a Change's current step started from (df-leash #2), or None for HEAD.

    The step started when its last step receipt (a `transition` or a `gap-reopen`) was written;
    the commit before the one that recorded that receipt is where the step's own commits begin.
    A Change with no such receipt started with the commit that added it. None when that commit
    is not made yet: the uncommitted diff is the whole step.
    """
    root = Path(product_root)
    try:
        data = yaml.safe_load((Path(change_dir) / "change.yaml").read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        return None
    change_id = str((data.get("id") if isinstance(data, dict) else None) or Path(change_dir).name)
    text = (root / ".deltafuse" / "transitions.jsonl")
    lines = text.read_text(encoding="utf-8").splitlines() if text.is_file() else []
    digest = None
    for entry in _json_rows(lines):
        if entry.get("change") == change_id and (entry.get("kind") == "transition" or rewind_gate(entry)):
            digest = entry.get("receipt") if isinstance(entry.get("receipt"), str) else digest
    if digest:
        found = _git(root, "log", "--reverse", "--format=%H", "-S", digest, "HEAD", "--",
                     ".deltafuse/transitions.jsonl")
    else:
        rel = (Path(change_dir).resolve() / "change.yaml").relative_to(root.resolve()).as_posix()
        found = _git(root, "log", "--reverse", "--format=%H", "--diff-filter=A", "HEAD", "--", rel)
    first = next((line.strip() for line in (found.stdout or "").splitlines() if line.strip()), None)
    if found.returncode != 0 or first is None:
        return None
    parent = _git(root, "rev-parse", "--verify", "--quiet", f"{first}^")
    return (parent.stdout or "").strip() or first if parent.returncode == 0 else first


def merge_base(product_root: Path, base: str, head: str | None) -> str:
    """The commit `head` left `base`'s line at: what a `base...head` diff is taken from, and so
    the base a journal or a record is compared with (df-leash #15)."""
    proc = _git(Path(product_root), "merge-base", base, head or "HEAD")
    found = (proc.stdout or "").strip()
    if proc.returncode != 0 or not found:
        err = (proc.stderr or proc.stdout or "git merge-base failed").strip()
        raise LeashError(f"leash could not find where {head or 'HEAD'} left {base}: {err}")
    return found


def _git_names(root: Path, *args: str, what: str) -> list[str]:
    """Path names a git listing command prints, NUL-separated and unquoted.

    Audit 2026-11-16 (df-leash #4): under `core.quotePath` (git's default) a name with a byte
    above 0x7f comes out quoted and octal-escaped ("src/\\320\\274...py"), matched no glob, and a
    Cyrillic file in src/ was never judged. `-z` prints names raw; git writes them in UTF-8.
    """
    proc = subprocess.run(
        # `-z` right after the subcommand: after a `--` it would be read as a path.
        ["git", "-c", "core.quotePath=false", args[0], "-z", *args[1:]], cwd=root, capture_output=True,
        check=False,
    )
    if proc.returncode != 0:
        err = (proc.stderr or proc.stdout or b"").decode("utf-8", errors="replace").strip()
        raise LeashError(f"leash could not {what}: {err or 'git failed'}")
    return [name for name in proc.stdout.decode("utf-8", errors="surrogateescape").split("\0") if name]


SUBDIRECTORY = (
    "{root} is a subdirectory of the git repository at {top}. DeltaFuse supports a product only at "
    "the root of its repository (or with no git): the pre-commit hook and the leash read paths "
    "from the repository root, so nothing in a subdirectory would be judged. Give the product its "
    "own repository (a submodule works); a monorepo layout is a roadmap item"
)


def repository_layout_error(product_root: Path | str) -> str | None:
    """Why git cannot judge this product, or None (FW-2, owner's decision R4).

    A product one level below its repository root was installed without a word: the hook was not
    installed (`.git` is not there), and the leash compared repository-relative names
    (`svc/src/app.py`) with product-relative globs (`src/**`), so no edit was ever judged."""
    root = Path(product_root).resolve()
    probe = root
    while not probe.is_dir() and probe != probe.parent:
        probe = probe.parent
    prefix = _git(probe, "rev-parse", "--show-prefix")
    if prefix.returncode != 0:
        return None  # no git, or not in a work tree
    if not (prefix.stdout or "").strip() and probe == root:
        return None  # the repository root itself
    top = _git(probe, "rev-parse", "--show-toplevel")
    return SUBDIRECTORY.format(root=root, top=(top.stdout or "").strip() or "above it")


def hook_warning(product_root: Path | str, mode: str | None = None) -> str | None:
    """Why commits here are not judged although the leash is on, or None (FW-13).

    Hooks are not cloned, and `core.hooksPath` set after `init` moves git away from the hook that
    was installed. Either way every commit went unjudged and no command said so."""
    root = Path(product_root)
    mode = mode or load_leash_mode(root)
    if mode == "off" or not (root / ".git").exists():
        return None
    hooks = _git_hooks_dir(root, announce=False)
    hook = hooks / "pre-commit" if hooks is not None else None
    if hook is not None and hook.is_file():
        text = hook.read_text(encoding="utf-8", errors="replace")
        if HOOK_MARKER in text or ".deltafuse/hooks/pre-commit" in text:
            return None
    where = f"{hook} does not run the leash" if hook is not None else "core.hooksPath points outside this repository"
    return (
        f"workflow.leash is '{mode}', but the leash pre-commit hook is not active in this clone "
        f"({where}): commits are not judged here. Run `deltafuse init <product-root>` to install it "
        "(hooks are not cloned), or call .deltafuse/hooks/pre-commit from the hook git does run"
    )


def has_commit(product_root: Path) -> bool:
    return _git(Path(product_root), "rev-parse", "--verify", "--quiet", "HEAD").returncode == 0


def _chmod_exec(path: Path) -> None:
    try:
        path.chmod(path.stat().st_mode | 0o111)
    except OSError:
        return


def _remove_marked_hook(path: Path) -> None:
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8", errors="replace")
    if HOOK_MARKER not in text:
        return
    path.unlink()


def _git_hooks_dir(product_root: Path, *, announce: bool = True) -> Path | None:
    """The directory git runs this repository's hooks from, or None (no git, or one not ours).

    `git rev-parse --git-path hooks` answers for a plain repository, a submodule or a linked
    worktree (`.git` is a file naming the real git directory: a service that is a submodule of an
    aggregator repository) and honours `core.hooksPath` (df-leash #13: with husky or a team
    template git runs the hooks from there, and a hook in .git/hooks never ran). A hooksPath
    outside this repository and its git directory is shared with other repositories: the hook is
    not put there, and the human is told how to wire it.
    """
    git = product_root / ".git"
    if not git.exists():
        return None
    try:
        done = subprocess.run(["git", "rev-parse", "--git-path", "hooks", "--git-common-dir"],
                              cwd=product_root, capture_output=True, text=True)
    except OSError:
        return None
    lines = [line.strip() for line in (done.stdout or "").splitlines() if line.strip()]
    if done.returncode != 0 or len(lines) != 2:
        return git / "hooks" if git.is_dir() else None
    hooks, common = (Path(p) if Path(p).is_absolute() else product_root / p for p in lines)
    hooks, common = hooks.resolve(), common.resolve()
    own = (Path(product_root).resolve(), common)
    if not any(hooks == home or home in hooks.parents for home in own):
        if announce:
            print(
                f"deltafuse: core.hooksPath points at {hooks}, outside this repository; the leash "
                "pre-commit hook was not put there. Run .deltafuse/hooks/pre-commit from the "
                "pre-commit hook in that directory to have commits judged.",
                file=sys.stderr,
            )
        return None
    return hooks


def sync_leash_hook(product_root: Path, mode: str) -> None:
    """Install or remove the local git pre-commit hook. Never git push.

    `off` removes a hook we generated. `advisory` and `enforce` write the
    same script (`deltafuse leash` already exits 0 in advisory). A foreign
    pre-commit without the installer marker is left alone; a copy still
    lands under `.deltafuse/hooks/` for chaining.
    """
    root = Path(product_root)
    normalized = str(mode or "").strip().lower()
    if normalized not in LEASH_MODES:
        normalized = "off"
    managed = root / ".deltafuse" / "hooks" / "pre-commit"
    hooks_dir = _git_hooks_dir(root, announce=normalized != "off")
    git_hook = (hooks_dir / "pre-commit") if hooks_dir is not None else None
    if normalized == "off":
        _remove_marked_hook(managed)
        if git_hook is not None:
            _remove_marked_hook(git_hook)
        return
    managed.parent.mkdir(parents=True, exist_ok=True)
    managed.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")
    _chmod_exec(managed)
    if git_hook is None:
        return
    git_hook.parent.mkdir(parents=True, exist_ok=True)
    if git_hook.is_file():
        existing = git_hook.read_text(encoding="utf-8", errors="replace")
        if HOOK_MARKER not in existing:
            print(
                f"deltafuse: {git_hook} is a pre-commit hook DeltaFuse did not write and is left as it "
                "is; run .deltafuse/hooks/pre-commit from it to have commits judged by the leash.",
                file=sys.stderr,
            )
            return
    git_hook.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")
    _chmod_exec(git_hook)
