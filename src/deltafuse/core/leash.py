def _bytes_digest(product_root: Path, rel: str, *, head: str | None = None) -> str:
    data = _bytes_at(product_root, posix_relpath(rel), head=head)
    return hashlib.sha256(data).hexdigest() if data is not None else ""


def vouched_digests(product_root: Path, *, head: str | None = None) -> dict[str, set[str]]:
    """sha256 of every structural write whose writer is known, per path.

    Three writers leave a digest of what they wrote: the Artifact Writer
    (`result_sha256` in `.deltafuse/receipts/`), `deltafuse state`
    (`sha256` in its artifact-status receipt) and `decide` (`artifact_sha256`
    in the gate journal). A file whose bytes match none of them was written by
    hand. The digests are not keyed: like the journals, this proves the shape
    of the Core's path, not provenance (docs/contracts/leash.md).
    """
    root = Path(product_root)
    out: dict[str, set[str]] = {}

    def add(rel: Any, digest: Any) -> None:
        if isinstance(rel, str) and isinstance(digest, str) and digest:
            out.setdefault(posix_relpath(rel), set()).add(digest.removeprefix("sha256:").lower())

    receipt_names: list[str] = []
    if head:
        listing = _git(root, "ls-tree", "-r", "--name-only", head, ".deltafuse/receipts")
        receipt_names = [line for line in listing.stdout.splitlines() if line.endswith(".json")]
    else:
        folder = root / ".deltafuse" / "receipts"
        if folder.is_dir():
            receipt_names = [f".deltafuse/receipts/{p.name}" for p in folder.glob("*.json")]
    for rel in receipt_names:
        try:
            receipt = json.loads(_bytes_at(root, rel, head=head) or b"{}")
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        if isinstance(receipt, dict) and receipt.get("outcome", "committed") == "committed":
            add(receipt.get("target"), receipt.get("result_sha256"))
    for journal, digest_key in ((".deltafuse/transitions.jsonl", "sha256"),
                                (".deltafuse/gate-journal.jsonl", "artifact_sha256")):
        text = _bytes_at(root, journal, head=head)
        for entry in _json_rows((text or b"").decode("utf-8", errors="replace").splitlines()):
            add(entry.get("path"), entry.get(digest_key))
    return out


def hand_written_errors(
    product_root: Path, rel_path: str, *, head: str | None, vouched: dict[str, set[str]]
) -> list[str]:
    """A structural artifact whose bytes no known writer produced."""
    kind = structural_kind(rel_path)
    if kind is None:
        return []
    rel = posix_relpath(rel_path)
    data = _bytes_at(Path(product_root), rel, head=head)
    if data is None:
        return []  # deleted: the envelope decides
    if hashlib.sha256(data).hexdigest() in vouched.get(rel, set()):
        return []
    return [
        f"leash: '{rel}' was written by hand; write {kind} artifacts with "
        f"`deltafuse artifact write --kind {kind} --change <change-dir>` (roadmap item 1)"
    ]


def collect_ready_envelopes(queue: Any, product_root: Path, halt: Any) -> list[dict[str, Any]]:
    """Envelopes of ready Worker steps. Empty when through-mode is halted."""
    if halt is not None:
        return []
    out: list[dict[str, Any]] = []
    for item in getattr(queue, "ready", []) or []:
        env = build_envelope(item, product_root)
        if env:
            out.append(env)
    return out


def _covered_by(rel_path: str, envelopes: list[dict[str, Any]]) -> dict[str, Any] | None:
    for env in envelopes:
        writes = env.get("write")
        globs = [row for row in writes if isinstance(row, str)] if isinstance(writes, list) else []
        if path_in_envelope(rel_path, globs):
            return env
    return None



def capability_roots(product_root: Path | None) -> tuple[str, ...]:
    """What a task may write when its slice names no bounds (DF3-006): the code roots
    (`workflow.code_roots` when set, else src/** and tests/**; see code_write_globs) and
    the specification."""
    return code_write_globs(product_root) + ("docs/spec/**",)


def _glob_covers(task_glob: str, slice_glob: str) -> bool:
    """True when task_glob is bounded by slice_glob (path-prefix semantics)."""
    norm = lambda g: g.replace("\\", "/").strip().lstrip("/")
    task, sl = norm(task_glob), norm(slice_glob)
    if sl.endswith("/**"):
        base = sl[:-3]
        return task == base or task.startswith(base + "/")  # task == sl starts with base + "/"
    return task == sl


def task_envelope_errors(change_path: Path) -> list[str]:
    """SEC-04 / DF3-006: task allowed_paths must stay inside their slice
    target_paths (or the capability-catalog roots when the slice declares
    none). A task cannot widen its write envelope by editing YAML."""
    tasks_dir = change_path / "tasks"
    if not tasks_dir.is_dir():
        return []
    slice_bounds: dict[str, list[str]] = {}
    for sf, meta in iter_frontmatter(change_path / "slices", "*.md", "*.yaml"):
        bounds = [str(g) for g in meta.get("target_paths") or []]
        if bounds:
            slice_bounds[str(meta.get("id") or sf.stem)] = bounds

    # A slice that declares no target_paths is bounded by the capability roots
    # plus what the Change's route may write in Declare and Implement. The
    # roots alone (src, tests, docs/spec) never cover an ops route's
    # deploy/**, docs/ops/**, ops/**: every ops task was blocked, and the slice
    # that could widen it is outside the decompose envelope. The route's own
    # write globs are already the widest envelope it has.
    route, _ = load_change_route(change_path)
    product_root = product_root_of(change_path)
    route_globs = [
        glob
        for phase in ("declare", "implement")
        for glob in phase_write_globs(phase, route or DEFAULT_CHANGE_ROUTE, product_root)
        if not glob.replace("\\", "/").startswith("docs/changes")
    ]
    default_bounds = list(dict.fromkeys(list(capability_roots(product_root)) + route_globs))

    errors: list[str] = []
    for tf, meta in iter_frontmatter(tasks_dir):
        tid = str(meta.get("id") or tf.stem)
        sid = str(meta.get("slice") or "")
        bounds = slice_bounds.get(sid) or default_bounds
        for raw in meta.get("allowed_paths") or []:
            task_glob = str(raw)
            if not any(_glob_covers(task_glob, g) for g in bounds):
                # The bound, not a field name: slices carry no target_paths in
                # the schema, so "escapes target_paths" named nothing the
                # Worker could see or change (roadmap item 4, box B).
                errors.append(
                    f"Task {tid}: allowed_paths '{task_glob}' is outside what this Change may "
                    f"write; use paths under {', '.join(bounds)}"
                )
    return errors


def unreachable_green_errors(change_path: Path) -> list[str]:
    """A task that promises a requirement delta must be able to turn its Red green.

    Reference run ref-m03-345 (qwen3.8-27b, M03, 2026-10-07): Decompose split "write the
    tests" (TASK-001, allowed_paths tests/ only, src/** forbidden) from "implement" (TASK-002,
    depending on TASK-001). TASK-001's Red could never pass inside its own envelope, and it ran
    first: the reference proved it and halted. An older run (c336b-m01) closed the same split
    only by writing src/ outside the task's allowed_paths. A delta task that may change no
    product file is fine only after a task that may - so it must depend on one.
    """
    route, _ = load_change_route(change_path)
    if (route or DEFAULT_CHANGE_ROUTE) != "code":
        return []
    tasks_dir = change_path / "tasks"
    if not tasks_dir.is_dir():
        return []
    product_root = product_root_of(change_path)
    roots = configured_code_roots(product_root)
    if roots:
        # A module keeps code and tests under one root (svc/src/**): the root is the product.
        product_globs = list(roots)
    else:
        declare = set(phase_write_globs("declare", "code"))
        product_globs = [
            g for g in phase_write_globs("implement", "code")
            if g not in declare and not g.replace("\\", "/").startswith("docs/")
        ]
    tasks = {str(meta.get("id") or tf.stem): meta for tf, meta in iter_frontmatter(tasks_dir)}

    def owns_product(tid: str) -> bool:
        paths = [str(p) for p in tasks.get(tid, {}).get("allowed_paths") or []]
        return any(_glob_covers(p, g) for p in paths for g in product_globs)

    def depends_on_product(tid: str) -> bool:
        seen: set[str] = set()
        todo = [str(d) for d in tasks.get(tid, {}).get("depends_on") or []]
        while todo:
            dep = todo.pop()
            if dep in seen or dep not in tasks:
                continue
            seen.add(dep)
            if owns_product(dep):
                return True
            todo.extend(str(d) for d in tasks[dep].get("depends_on") or [])
        return False

    errors: list[str] = []
    for tid, meta in tasks.items():
        delta = str(meta.get("requirement_delta") or "").strip().lower()
        if delta in {"", "none"} or meta.get("status") in {"cancelled", "superseded"}:
            continue
        if owns_product(tid) or depends_on_product(tid):
            continue
        paths = [str(p) for p in meta.get("allowed_paths") or []]
        errors.append(
            f"Task {tid} promises requirement_delta '{delta}' but may change no product file "
            f"(allowed_paths {paths}) and depends on no task that may: its Red tests could never "
            "turn Green. Give it the product paths its tests need, merge it with the task that "
            "changes the product, or make it depend on that task"
        )
    return errors


def _nonempty_lines(text: str | None) -> list[str]:
    return [line.strip() for line in (text or "").splitlines() if line.strip()]


def _journal_lines(
    product_root: Path, rel_path: str, *, base: str | None, head: str | None
) -> tuple[list[str], list[str]]:
    old = _nonempty_lines(_git_show(product_root, base or "HEAD", rel_path))
    return old, _nonempty_lines(_content_at(product_root, rel_path, head=head))


def _change_dirs(product_root: Path) -> dict[str, Path]:
    """Change id -> directory for every live Change package."""
    out: dict[str, Path] = {}
    for change_yaml in sorted((product_root / "docs" / "changes").glob("*/change.yaml")):
        try:
            data = yaml.safe_load(change_yaml.read_text(encoding="utf-8")) or {}
        except Exception:
            data = {}
        change_id = data.get("id") if isinstance(data, dict) else None
        out[str(change_id or change_yaml.parent.name)] = change_yaml.parent
    return out


def core_journal_errors(
    product_root: Path,
    name: str,
    *,
    base: str | None = None,
    head: str | None = None,
) -> list[str]:
    """DF3-007: why a Core journal diff is not a Core-shaped append (empty = valid).

    The Worker runs `deltafuse advance` and the human runs `deltafuse decide`
    inside the same working tree, so the journals legitimately change between
    commits. A diff is accepted only when it appends entries the Core would have
    written: existing lines untouched, every transition receipt digest intact
    and the chain replayable, the gate journal chain and head verified.
    """
    from deltafuse.core import gate_receipts
    from deltafuse.core.transitions import _receipt, receipt_chain_errors

    root = Path(product_root)
    if name == "journal-head":
        # The head digest moves with every gate receipt; it is valid exactly
        # when it matches the verified gate journal.
        return gate_receipts.journal_errors(root)
    rel = f".deltafuse/{name}"
    old, new = _journal_lines(root, rel, base=base, head=head)
    if new[: len(old)] != old:
        return ["existing entries were edited, removed or reordered; Core journals are append-only"]
    appended = new[len(old):]
    errors: list[str] = []
    if name == "transitions.jsonl":
        touched: set[str] = set()
        for number, raw in enumerate(appended, start=len(old) + 1):
            try:
                entry = json.loads(raw)
            except json.JSONDecodeError:
                errors.append(f"line {number} is not JSON")
                continue
            if not isinstance(entry, dict) or entry.get("kind") not in CORE_RECEIPT_KINDS:
                errors.append(f"line {number} is not a Core transition receipt")
                continue
            body = {key: value for key, value in entry.items() if key != "receipt"}
            if entry.get("receipt") != _receipt(body):
                errors.append(f"line {number}: receipt digest does not match the entry")
                continue
            if isinstance(entry.get("change"), str):
                touched.add(entry["change"])
        if errors:
            return errors
        dirs = _change_dirs(root)
        for change_id in sorted(touched):
            change_dir = dirs.get(change_id)
            if change_dir is not None:
                errors.extend(
                    f"{change_id}: {err}" for err in receipt_chain_errors(root, change_dir)
                )
        return errors
    if name == "gate-journal.jsonl":
        for number, raw in enumerate(appended, start=len(old) + 1):
            try:
                entry = json.loads(raw)
            except json.JSONDecodeError:
                errors.append(f"line {number} is not JSON")
                continue
            # journal_errors skips legacy lines, but has_click still reads
            # them: an appended line without the current receipt format
            # would count as a click without any integrity claim.
            if not isinstance(entry, dict) or entry.get("receipt_version") != gate_receipts.RECEIPT_VERSION:
                errors.append(f"line {number} is not a current-format gate receipt")
        if errors:
            return errors
        return gate_receipts.journal_errors(root)
    return [f"unknown Core journal '{name}'"]


def core_status_writes(
    product_root: Path,
    *,
    base: str | None = None,
    head: str | None = None,
) -> dict[str, list[str]]:
    """Task and slice files the Core rewrote through `deltafuse state` since ``base``.

    `deltafuse state` is how a Worker asks the Core to move a slice or task
    status; the Core rewrites the frontmatter and appends an artifact-status
    receipt. Those files lie outside the step envelope on purpose - a Worker
    must not hand-edit them - so the guard recognises the Core's rewrite by its
    receipt and by its content: only `status` changed, from the first receipt's
    `from` to the last receipt's `to`, the rest of the frontmatter and the body
    as before. Maps each path to the reasons it fails (empty = a pure Core
    status write).
    """
    root = Path(product_root)
    old, new = _journal_lines(root, ".deltafuse/transitions.jsonl", base=base, head=head)
    if new[: len(old)] != old:
        return {}  # core_journal_errors reports the rewrite; nothing is vouched for
    dirs = _change_dirs(root)
    moves: dict[str, list[dict[str, Any]]] = {}
    for entry in _json_rows(new[len(old):]):
        if entry.get("kind") != "artifact-status":
            continue
        folder = {"task": "tasks", "slice": "slices"}.get(str(entry.get("artifact")))
        change_dir = dirs.get(str(entry.get("change")))
        if folder is None or change_dir is None or not isinstance(entry.get("artifact_id"), str):
            continue
        home = (change_dir / folder).relative_to(root).as_posix()
        rel = (change_dir / folder / f"{entry['artifact_id']}.md").relative_to(root).as_posix()
        recorded = entry.get("path")
        if isinstance(recorded, str):
            # A task file may be TASK-NNN-<slug>.md; the Core records which one
            # it rewrote. Only a file of this Change's folder is ever accepted.
            recorded = posix_relpath(recorded)
            if recorded.startswith(home + "/") and "/" not in recorded[len(home) + 1:]:
                rel = recorded
        moves.setdefault(rel, []).append(entry)

    out: dict[str, list[str]] = {}
    for rel, entries in moves.items():
        reasons: list[str] = []
        try:
            before_meta, before_body = parse_frontmatter(_git_show(root, base or "HEAD", rel) or "")
            after_meta, after_body = parse_frontmatter(_content_at(root, rel, head=head) or "")
        except Exception as ex:
            out[rel] = [f"cannot compare with the base: {ex}"]
            continue
        if before_meta.get("status") != entries[0].get("from"):
            reasons.append(f"status at the base is not the receipt's '{entries[0].get('from')}'")
        if after_meta.get("status") != entries[-1].get("to"):
            reasons.append(f"status is not the receipt's '{entries[-1].get('to')}'")
        rest_before = {k: v for k, v in before_meta.items() if k != "status"}
        rest_after = {k: v for k, v in after_meta.items() if k != "status"}
        if rest_before != rest_after:
            reasons.append("frontmatter changed beyond status")
        if before_body.strip() != after_body.strip():
            reasons.append("body changed")
        out[rel] = reasons
    return out


def collect_chain_envelopes(
    product_root: Path,
    *,
    base: str | None = None,
    dirty: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Envelopes of the lifecycle steps each Change worked through since ``base``.

    The ready queue names only the next step, so it alone judges a finished
    step's writes against the step that follows it: request.md written by
    intake reads as outside the analyze envelope, and a commit right after
    `deltafuse advance` is refused. The steps are taken from the transition
    receipts, which core_journal_errors verifies: from the step after the last
    gate at ``base`` up to the step after the last gate now.

    Declare and implement are per task, and task progress is not in the
    transition chain. Their envelopes come from the tasks whose file changed
    since ``base`` - `deltafuse state` rewrites the task file on every task
    transition - so a task the Worker never touched adds no paths.
    """
    from deltafuse.core.queue import _item_for_step, _load_tasks
    from deltafuse.core.steps import STEP_CONTRACTS, STEP_ORDER

    root = Path(product_root)
    gate_step = {spec["gate"]: step for step, spec in STEP_CONTRACTS.items()}

    def last_gates(lines: list[str]) -> dict[str, str]:
        out: dict[str, str] = {}
        for entry in _json_rows(lines):
            if (
                entry.get("kind") == "transition"
                and isinstance(entry.get("change"), str)
                and entry.get("gate") in gate_step
            ):
                out[entry["change"]] = entry["gate"]
        return out

    def step_after(gate: str | None) -> int:
        if gate is None:
            return 0
        return min(STEP_ORDER.index(gate_step[gate]) + 1, len(STEP_ORDER) - 1)

    rel = ".deltafuse/transitions.jsonl"
    at_base, now = _journal_lines(root, rel, base=base, head=None)
    base_last, now_last = last_gates(at_base), last_gates(now)
    changed = {posix_relpath(path) for path in (dirty or [])}

    envelopes: list[dict[str, Any]] = []
    for change_id, change_dir in _change_dirs(root).items():
        low, high = step_after(base_last.get(change_id)), step_after(now_last.get(change_id))
        if high < low:
            continue  # a rewound chain is receipt_chain_errors' business, not a wider fence
        rel_dir = change_dir.relative_to(root).as_posix()
        for step in STEP_ORDER[low : high + 1]:
            items: list[WorkItem] = []
            if step in {"declare", "implement"}:
                # gemma-31b M01 (2026-09-26): evidence written, the gate advanced and the
                # step closed in one go, `state` called later - the task file was not
                # dirty yet, so its own evidence was judged against the step after it.
                # A task whose evidence for this step is dirty is the step's task too.
                phases = {"declare": ("red",), "implement": ("green", "regression")}[step]
                for task_id, _, task_file, _ in _load_tasks(change_dir):
                    task_rel = task_file.relative_to(root).as_posix()
                    wrote_evidence = any(
                        f"{rel_dir}/evidence/{phase}/{task_id}.yaml" in changed for phase in phases
                    )
                    if task_rel in changed or wrote_evidence:
                        items.append(
                            _item_for_step(
                                step, change_id=change_id, path=rel_dir, task=task_id,
                                task_path=task_rel, reason="receipt chain since base",
                            )
                        )
            else:
                items.append(
                    _item_for_step(step, change_id=change_id, path=rel_dir, reason="receipt chain since base")
                )
            for item in items:
                env = build_envelope(item, root)
                if env:
                    envelopes.append(env)
    return envelopes


def check_paths(
    rel_paths: list[str],
    envelopes: list[dict[str, Any]] | None = None,
    *,
    envelope: dict[str, Any] | None = None,  # one envelope, the bench's form of the call
    baseline: str = "draft",
    product_root: Path | None = None,
    base: str | None = None,
    head: str | None = None,
) -> list[str]:
    """Return violation messages for dirty paths.

    A path is allowed when a ready envelope covers it. Code/ops/deploy
    paths with no covering Change are orphans. `docs/spec/**` is an
    orphan only after `project.baseline: accepted` (Bootstrap may write
    spec while the baseline is draft). Ready step + uncovered Change
    artifact is still an LS-002 miss.

    Core journals (DF3-007): with ``product_root`` they are verified against
    ``base`` instead of refused outright, because every `deltafuse advance`
    and `decide` appends to them; without it any change is refused.
    """
    if envelopes is None:
        env_list = [envelope] if envelope is not None else []
    else:
        env_list = list(envelopes)
    errors: list[str] = []
    steps = [str(env.get("step") or "?") for env in env_list]
    step_label = ", ".join(dict.fromkeys(steps)) if steps else ""
    # Say what the phase is for: a refusal alone sent a Worker into repeating it.
    phase_hint = (
        " (declare writes tests only; product code is written in implement)"
        if step_label == "declare"
        else ""
    )
    status_writes = (
        core_status_writes(product_root, base=base, head=head) if product_root is not None else {}
    )
    vouched = vouched_digests(product_root, head=head) if product_root is not None else {}
    for raw in _unique(rel_paths):
        # DF3-007 runs before the exemptions: `.deltafuse/**` is exempt as a
        # whole, so checking it second would make the Core-owned guard dead code.
        top, _, tail = posix_relpath(raw).partition("/")
        if top == ".deltafuse" and tail in CORE_OWNED:
            if product_root is not None and tail in CORE_JOURNALS:
                reasons = core_journal_errors(product_root, tail, base=base, head=head)
                if not reasons:
                    continue
                errors.extend(
                    f"leash: '{raw}' changed outside the deltafuse CLI: {reason} (DF3-007)"
                    for reason in reasons
                )
                continue
            errors.append(
                f"leash: '{raw}' is Core-owned; mutate it only through "
                f"{CORE_OWNED_WRITER.get(tail, 'the deltafuse CLI')} (DF3-007)"
            )
            continue
        if raw.startswith(".git/") or is_exempt_path(raw):
            continue
        if _covered_by(raw, env_list) is not None:
            if product_root is not None:
                errors.extend(hand_written_errors(product_root, raw, head=head, vouched=vouched))
            continue
        if posix_relpath(raw) == CATALOG_REL and product_root is not None:
            # The catalog belongs to the human, and no step envelope holds it.
            # `deltafuse capability propose` adds a draft in Analyze and leaves
            # the digest of what it wrote; bytes no receipt vouches for are a
            # hand edit (q8 decision).
            if _bytes_digest(product_root, raw, head=head) in vouched.get(CATALOG_REL, set()):
                continue
            # Not vouched: fall through to the ordinary checks. The catalog is
            # the human's file and a human edit is not a Worker violation.
        status_reasons = status_writes.get(posix_relpath(raw))
        if status_reasons is not None:
            if not status_reasons:
                continue  # a `deltafuse state` rewrite, vouched for by its receipt
            errors.extend(
                f"leash: '{raw}' is outside the {step_label} write envelope and not a pure "
                f"Core status write: {reason}"
                for reason in status_reasons
            )
            continue
        if is_product_path(raw, baseline=baseline, product_root=product_root):
            if not env_list:
                errors.append(f"leash: '{raw}' is not covered by any Change")
            else:
                errors.append(
                    f"leash: '{raw}' is outside the {step_label} write envelope{phase_hint}"
                )
            continue
        if product_root is not None and reopen_archive_path(product_root, raw):
            continue  # written by the human's `deltafuse decide --status reopened`
        if product_root is not None and reopened_red_path(product_root, raw):
            # a reopened task is declared again past Declare; its Red is still the Core's
            errors.extend(hand_written_errors(product_root, raw, head=head, vouched=vouched))
            continue
        if is_change_artifact(raw) and env_list:
            # gemma-334c/glm47flash: a Worker put the Writer's input JSON in a
            # `.deltafuse/tmp/` inside the Change directory (224 refusals in two
            # runs); the exemption is for the one at the product root.
            scratch = (
                " (the Writer's input file belongs in `.deltafuse/tmp/` at the product root, "
                "not inside the Change directory)"
                if "/.deltafuse/tmp/" in posix_relpath(raw)
                else ""
            )
            errors.append(
                f"leash: '{raw}' is outside the {step_label} write envelope{scratch}"
            )
    return errors



def git_dirty_paths(
    product_root: Path,
    *,
    base: str | None = None,
    head: str | None = None,
) -> list[str]:
    """Changed paths as repo-relative posix names.

    DF3-003 / SEC-01: pass ``base`` (and optionally ``head``) with exact SHAs to
    diff a commit range — a clean PR/push checkout has no local diff, so CI must
    judge the committed range. Untracked files remain a separate always-on check.
    """
    root = product_root.resolve()
    probe = _git(root, "rev-parse", "--show-toplevel")
    if probe.returncode != 0:
        err = (probe.stderr or probe.stdout or "git rev-parse failed").strip()
        raise LeashError(f"leash needs a git repository: {err}")
    diff_args = ["diff", "--name-only"]
    if base:
        diff_args.append(f"{base}..{head or 'HEAD'}")
    else:
        # A repository with no commits has no HEAD to diff against, and git says
        # so in its own words ("fatal: ambiguous argument 'HEAD'"). That is the
        # state of every freshly inited product at the moment run/SKILL.md tells
        # the Worker to run leash. Diffing the empty tree instead would list the
        # whole scaffold as the Worker's writes and bury the real answer under it.
        if _git(root, "rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
            raise LeashError(
                "leash needs one commit to diff against and this repository has no commit yet, "
                "so there is no baseline a write envelope can be judged against. Make an initial "
                "commit of the installed scaffold (`git add -A` then `git commit`), then run "
                "`deltafuse leash` again"
            )
        diff_args.append("HEAD")
    tracked = _git(root, *diff_args)
    if tracked.returncode != 0:
        err = (tracked.stderr or tracked.stdout or "git diff failed").strip()
        raise LeashError(f"leash could not read git diff: {err}")
    untracked = _git(root, "ls-files", "--others", "--exclude-standard")
    if untracked.returncode != 0:
        err = (untracked.stderr or untracked.stdout or "git ls-files failed").strip()
        raise LeashError(f"leash could not list untracked files: {err}")
    # _unique normalizes slashes and drops blank lines.
    return _unique((tracked.stdout or "").splitlines() + (untracked.stdout or "").splitlines())


def _chmod_exec(path: Path) -> None:
    try:
        path.chmod(path.stat().st_mode | 0o111)
    except OSError:
        return


def _remove_marked_hook(path: Path) -> None:
    if not path.is_file():
        return
    text = path.read_text(encoding="utf-8", errors="replace")
    if HOOK_MARKER not in text:
        return
    path.unlink()


def _git_hooks_dir(product_root: Path) -> Path | None:
    git = product_root / ".git"
    if git.is_dir():
        return git / "hooks"
    return None


def sync_leash_hook(product_root: Path, mode: str) -> None:
    """Install or remove the local git pre-commit hook. Never git push.

    `off` removes a hook we generated. `advisory` and `enforce` write the
    same script (`deltafuse leash` already exits 0 in advisory). A foreign
    pre-commit without the installer marker is left alone; a copy still
    lands under `.deltafuse/hooks/` for chaining.
    """
    root = Path(product_root)
    normalized = str(mode or "").strip().lower()
    if normalized not in LEASH_MODES:
        normalized = "off"
    managed = root / ".deltafuse" / "hooks" / "pre-commit"
    hooks_dir = _git_hooks_dir(root)
    git_hook = (hooks_dir / "pre-commit") if hooks_dir is not None else None
    if normalized == "off":
        _remove_marked_hook(managed)
        if git_hook is not None:
            _remove_marked_hook(git_hook)
        return
    managed.parent.mkdir(parents=True, exist_ok=True)
    managed.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")
    _chmod_exec(managed)
    if git_hook is None:
        return
    git_hook.parent.mkdir(parents=True, exist_ok=True)
    if git_hook.is_file():
        existing = git_hook.read_text(encoding="utf-8", errors="replace")
        if HOOK_MARKER not in existing:
            return
    git_hook.write_text(HOOK_SCRIPT, encoding="utf-8", newline="\n")
    _chmod_exec(git_hook)
